export const getServiceBySlug = (slug: string) =>
  services.find((s) => s.slug === slug);

export const getServicesByCategory = (cat: CategoryKey) =>
  services.filter((s) => s.categories.includes(cat));

export const sortServices = (
  list: Service[],
  mode: 'default' | 'popularity' | 'newest' | 'priceDesc' | 'priceAsc'
) => {
  const copy = [...list];
  switch (mode) {
    case 'popularity':
      return copy.sort((a, b) => a.popularityOrder - b.popularityOrder);
    case 'newest':
      return copy.sort((a, b) => a.newestOrder - b.newestOrder);
    case 'priceDesc':
      return copy.sort((a, b) => b.price - a.price);
    case 'priceAsc':
      return copy.sort((a, b) => a.price - b.price);
    default:
      return copy.sort((a, b) => a.defaultOrder - b.defaultOrder);
  }
};

